test "originalProfile returns a self-consistent builtin sRGB ICC" {
	const profile = originalProfile(&color_encoding.ColorEncoding{}) orelse return error.TestUnexpectedResult;
	try testing.expectEqual(@as(usize, 588), profile.len);
	try testing.expectEqual(@as(u32, @intCast(profile.len)), std.mem.readInt(u32, @ptrCast(profile[0..4]), .big));
	try testing.expectEqualSlices(u8, "RGB XYZ ", profile[16..24]);
	try testing.expectEqualSlices(u8, "acsp", profile[36..40]);
}

test "originalProfile returns deterministic profiles for linear and gray structured encodings" {
	var linear = color_encoding.ColorEncoding{};
	linear.tf.transfer_function = .linear;
	const linear_profile = originalProfile(&linear) orelse return error.TestUnexpectedResult;
	try testing.expectEqual(@as(usize, 600), linear_profile.len);
	try testing.expectEqualSlices(u8, "RGB XYZ ", linear_profile[16..24]);
	try testing.expectEqualSlices(u8, "acsp", linear_profile[36..40]);

	var gray = color_encoding.ColorEncoding{};
	gray.color_space = .gray;
	const gray_profile = originalProfile(&gray) orelse return error.TestUnexpectedResult;
	try testing.expectEqual(@as(usize, 348), gray_profile.len);
	try testing.expectEqualSlices(u8, "GRAYXYZ ", gray_profile[16..24]);
	try testing.expectEqualSlices(u8, "acsp", gray_profile[36..40]);
}

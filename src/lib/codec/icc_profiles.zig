const testing = std.testing;

test "originalProfile returns a self-consistent builtin sRGB ICC" {
	const profile = originalProfile(&color_encoding.ColorEncoding{}) orelse return error.TestUnexpectedResult;
	try testing.expectEqual(@as(usize, 588), profile.len);
	try testing.expectEqual(@as(u32, @intCast(profile.len)), std.mem.readInt(u32, @ptrCast(profile[0..4]), .big));
	try testing.expectEqualSlices(u8, "RGB XYZ ", profile[16..24]);
	try testing.expectEqualSlices(u8, "acsp", profile[36..40]);
}

test "originalProfile rejects unsupported structured encodings" {
	var linear = color_encoding.ColorEncoding{};
	linear.tf.transfer_function = .linear;
	try testing.expect(originalProfile(&linear) == null);

	var gray = color_encoding.ColorEncoding{};
	gray.color_space = .gray;
	try testing.expect(originalProfile(&gray) == null);
}

const std = @import("std");
const color_encoding = @import("color_encoding.zig");

/// Returns the current deterministic ICC approximation surface for decoder-side
/// structured color encodings while full embedded-ICC codestream support is still pending.
pub fn originalProfile(ce: *const color_encoding.ColorEncoding) ?[]const u8 {
	if (isBuiltinSrgb(ce)) return &srgb_builtin_profile;
	if (isBuiltinLinearSrgb(ce)) return &linear_srgb_builtin_profile;
	if (isBuiltinGraySrgb(ce)) return &gray_srgb_builtin_profile;
	if (!ce.want_icc and ce.isGray() and ce.white_point == .d65 and !ce.tf.have_gamma and ce.tf.transfer_function == .linear and ce.rendering_intent == .relative) return &linear_gray_builtin_profile;
	return null;
}

/// Matches the current built-in ICC bridge for default relative-intent RGB sRGB.
fn isBuiltinSrgb(ce: *const color_encoding.ColorEncoding) bool {
	return !ce.want_icc and
		ce.color_space == .rgb and
		ce.white_point == .d65 and
		ce.primaries == .srgb and
		!ce.tf.have_gamma and
		ce.tf.transfer_function == .srgb and
		ce.rendering_intent == .relative;
}

/// Matches the current built-in ICC bridge for default relative-intent linear sRGB.
fn isBuiltinLinearSrgb(ce: *const color_encoding.ColorEncoding) bool {
	return !ce.want_icc and
		ce.color_space == .rgb and
		ce.white_point == .d65 and
		ce.primaries == .srgb and
		!ce.tf.have_gamma and
		ce.tf.transfer_function == .linear and
		ce.rendering_intent == .relative;
}

/// Matches the current built-in ICC bridge for default relative-intent grayscale sRGB.
fn isBuiltinGraySrgb(ce: *const color_encoding.ColorEncoding) bool {
	return !ce.want_icc and
		ce.color_space == .gray and
		ce.white_point == .d65 and
		!ce.tf.have_gamma and
		ce.tf.transfer_function == .srgb and
		ce.rendering_intent == .relative;
}


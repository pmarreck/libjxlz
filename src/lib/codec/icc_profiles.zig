const std = @import("std");
const color_encoding = @import("color_encoding.zig");

/// Returns the first deterministic ICC approximation surface for decoder-side
/// structured color encodings while full embedded-ICC codestream support is still pending.
pub fn originalProfile(ce: *const color_encoding.ColorEncoding) ?[]const u8 {
	if (isBuiltinSrgb(ce)) return &srgb_builtin_profile;
	return null;
}

/// Matches the current narrow built-in ICC bridge exactly: default relative-intent
/// RGB sRGB with the standard enum-coded transfer function and no embedded ICC flag.
fn isBuiltinSrgb(ce: *const color_encoding.ColorEncoding) bool {
	return !ce.want_icc and
		ce.color_space == .rgb and
		ce.white_point == .d65 and
		ce.primaries == .srgb and
		!ce.tf.have_gamma and
		ce.tf.transfer_function == .srgb and
		ce.rendering_intent == .relative;
}

